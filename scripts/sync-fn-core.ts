// Copies the pure rules the Edge Functions share with the dashboard (segments.ts,
// status.ts, csv.ts, exportRows.ts and what it imports: overtime.ts, xlsx.ts, zip.ts,
// from packages/core) into
// supabase/functions/_shared/core, because the local Edge runtime only sees
// supabase/functions. `luxon` becomes the npm: import Deno resolves. `--check` writes
// nothing and fails when a copy is stale (CI).
//
// Usage: pnpm core:fn [--check]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const FILES = [
  "csv.ts",
  "exportRows.ts",
  "overtime.ts",
  "segments.ts",
  "status.ts",
  "xlsx.ts",
  "zip.ts",
];
const check = process.argv.includes("--check");

const root = new URL("../", import.meta.url);
const luxon = (
  JSON.parse(readFileSync(new URL("packages/core/package.json", root), "utf8")) as {
    dependencies: { luxon: string };
  }
).dependencies.luxon;
const outDir = new URL("supabase/functions/_shared/core/", root);

let stale = false;
for (const name of FILES) {
  const source = readFileSync(new URL(`packages/core/src/${name}`, root), "utf8");
  const header =
    `// Generated by \`pnpm core:fn\` from packages/core/src/${name}. Do not edit.\n` +
    "// Edit the source, run the command, and commit both (CI checks they match).\n\n";
  const generated = header + source.replace(/from "luxon";/g, `from "npm:luxon@${luxon}";`);
  const target = new URL(name, outDir);
  const current = (() => {
    try {
      return readFileSync(target, "utf8");
    } catch {
      return null;
    }
  })();
  if (current === generated) continue;
  if (check) {
    stale = true;
    console.error(`stale: ${target.pathname.replace(root.pathname, "")}`);
  } else {
    mkdirSync(outDir, { recursive: true });
    writeFileSync(target, generated);
    console.log(`wrote ${target.pathname.replace(root.pathname, "")}`);
  }
}
if (stale) {
  console.error("Run `pnpm core:fn` and commit the result.");
  process.exit(1);
}
