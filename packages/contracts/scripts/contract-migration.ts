// Writes a new Supabase migration that stores the current agent-event JSON Schema
// in internal.contract_schemas, where agent_events validates against it. Run after
// `pnpm contracts:gen` whenever events.ts changes; commit the migration with it.
import { readFileSync, writeFileSync } from "node:fs";

const schema = readFileSync(
  new URL("../generated/agent-event.schema.json", import.meta.url),
  "utf8",
);
const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
const out = new URL(
  `../../../supabase/migrations/${stamp}_contract_agent_event.sql`,
  import.meta.url,
);
const sql = `-- Generated by \`pnpm contracts:migration\` from packages/contracts/src/events.ts.
-- Do not edit; change the Zod schema and generate a new migration instead.
insert into internal.contract_schemas (name, schema)
values ('agent_event', $schema$${JSON.stringify(JSON.parse(schema))}$schema$::jsonb)
on conflict (name) do update set schema = excluded.schema, updated_at = now();
`;
writeFileSync(out, sql);
console.log(`wrote ${out.pathname}`);
